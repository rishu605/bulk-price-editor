#!/usr/bin/env node
/**
 * `prisma migrate deploy`, over a direct connection when there is one (#810).
 *
 * Behind PgBouncer in transaction mode, `DATABASE_URL` points at the pooler, and Migrate
 * cannot run there: it takes a session-level advisory lock to stop two deploys migrating
 * at once, and transaction pooling hands each statement whichever server connection is
 * free, so the lock is taken on one connection and the migration runs on another. Prisma's
 * own answer is `directUrl` in the schema -- but a schema `env()` that is unset fails every
 * Prisma command, so declaring it would break every deploy and every laptop that has not
 * set it yet.
 *
 * So the web service's boot runs this instead: `DATABASE_DIRECT_URL` when it is set, and
 * otherwise `DATABASE_URL`, exactly as before. Only migrations use the direct URL; the
 * app's own client always goes through `DATABASE_URL`. See `docs/deploying-to-railway.md`.
 *
 *   npm run setup   # prisma generate && tsx scripts/migrate.ts
 */

import { spawnSync } from "node:child_process";

const direct = process.env.DATABASE_DIRECT_URL?.trim();
const env = direct ? { ...process.env, DATABASE_URL: direct } : process.env;

// `npx` rather than a resolved path: it finds the project's own Prisma CLI, the one the
// client was generated by, wherever npm put it.
const result = spawnSync("npx", ["prisma", "migrate", "deploy"], { stdio: "inherit", env });

if (result.error) {
  console.error(`[migrate] could not start prisma: ${result.error.message}`);
  process.exit(1);
}
process.exit(result.status ?? 1);
